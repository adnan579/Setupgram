/** @format */

import { NextResponse } from "next/server";
import { getDb } from "../../../lib/mongodb";
import { Resend } from "resend";
import { checkRateLimit, getClientIp } from "../../../lib/rateLimit";
import { cleanText, escapeHtml } from "../../../lib/validate";
import { BUDGET_OPTIONS, TIMELINE_OPTIONS, pickOption, optionLabel } from "../../../lib/leadOptions";

const resend = new Resend(process.env.RESEND_API_KEY);

export async function POST(request: Request) {
  try {
    const ip = getClientIp(request);
    const { allowed, retryAfterSeconds } = await checkRateLimit(`contact:${ip}`, 5, 10 * 60 * 1000);
    if (!allowed) {
      return NextResponse.json(
        {
          success: false,
          message: `Too many submissions. Please try again in ${Math.ceil(retryAfterSeconds / 60)} minute(s).`,
        },
        { status: 429 },
      );
    }

    const body = await request.json().catch(() => null);
    if (!body || typeof body !== "object") {
      return NextResponse.json(
        { success: false, message: "Invalid request." },
        { status: 400 },
      );
    }

    // Clean + cap every public input (non-strings become "")
    const name = cleanText(body.name, 100);
    const email = cleanText(body.email, 254);
    const phone = cleanText(body.phone, 30);
    const service = cleanText(body.service, 50) || "other";
    // Optional dropdowns: only the known values are accepted, anything else becomes ""
    const budget = pickOption(BUDGET_OPTIONS, body.budget);
    const timeline = pickOption(TIMELINE_OPTIONS, body.timeline);
    const message = cleanText(body.message, 5000, { multiline: true });

    // Validation
    if (!name || !email || !message) {
      return NextResponse.json(
        { success: false, message: "Name, email, and message are required." },
        { status: 400 },
      );
    }
    const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
    if (!emailRegex.test(email)) {
      return NextResponse.json(
        { success: false, message: "Invalid email address." },
        { status: 400 },
      );
    }

    const db = await getDb();

    const lead = {
      name,
      email,
      phone,
      service,
      budget,
      timeline,
      message,
      status: "NEW",
      createdAt: new Date(),
    };
    await db.collection("leads").insertOne(lead);

    // The lead is already saved. A failed notification email must NOT turn the
    // response into an error (the visitor would resubmit and create duplicates).
    // Resend v3 returns { data, error } instead of throwing, so check both.
    try {
      const { error: emailError } = await resend.emails.send({
        from: "SetupGram <onboarding@resend.dev>",
        to: "info@setupgram.com",
        subject: `🚀 New Lead: ${name} — ${service}`,
        html: `
        <div style="font-family:sans-serif;max-width:600px;margin:0 auto;background:#050505;color:#e2e8f0;padding:32px;border-radius:12px;border:1px solid rgba(0,240,255,0.2)">
          <h2 style="color:#00f0ff;margin-bottom:24px">New Lead from SetupGram</h2>
          <table style="width:100%;border-collapse:collapse">
            <tr><td style="padding:8px 0;color:#94a3b8;width:120px">Name</td><td style="padding:8px 0;color:#fff;font-weight:600">${escapeHtml(name)}</td></tr>
            <tr><td style="padding:8px 0;color:#94a3b8">Email</td><td style="padding:8px 0"><a href="mailto:${escapeHtml(email)}" style="color:#00f0ff">${escapeHtml(email)}</a></td></tr>
            <tr><td style="padding:8px 0;color:#94a3b8">Phone</td><td style="padding:8px 0;color:#fff">${escapeHtml(phone) || "—"}</td></tr>
            <tr><td style="padding:8px 0;color:#94a3b8">Service</td><td style="padding:8px 0;color:#b026ff;font-weight:600;text-transform:uppercase">${escapeHtml(service)}</td></tr>
            <tr><td style="padding:8px 0;color:#94a3b8">Budget</td><td style="padding:8px 0;color:#fff">${escapeHtml(optionLabel(BUDGET_OPTIONS, budget)) || "—"}</td></tr>
            <tr><td style="padding:8px 0;color:#94a3b8">Timeline</td><td style="padding:8px 0;color:#fff">${escapeHtml(optionLabel(TIMELINE_OPTIONS, timeline)) || "—"}</td></tr>
            <tr><td style="padding:8px 0;color:#94a3b8;vertical-align:top">Message</td><td style="padding:8px 0;color:#e2e8f0;line-height:1.6">${escapeHtml(message).replace(/\n/g, "<br />")}</td></tr>
          </table>
          <div style="margin-top:32px;padding-top:24px;border-top:1px solid rgba(255,255,255,0.1)">
            <a href="https://setupgram.com/admin/leads" style="display:inline-block;padding:12px 24px;background:#00f0ff;color:#050505;font-weight:700;border-radius:8px;text-decoration:none">View in Admin Panel →</a>
          </div>
          <p style="color:#475569;font-size:12px;margin-top:24px">This email was auto-generated by SetupGram CRM.</p>
        </div>
      `,
      });
      if (emailError) {
        console.error("Lead notification email failed:", emailError);
      }
    } catch (emailErr) {
      console.error("Lead notification email threw:", emailErr);
    }

    return NextResponse.json(
      { success: true, message: "Message received. We'll be in touch shortly." },
      { status: 200 },
    );
  } catch (error) {
    console.error("Contact form error:", error);
    return NextResponse.json(
      { success: false, message: "Internal server error." },
      { status: 500 },
    );
  }
}
